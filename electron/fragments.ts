/** what fragments declared (player page ?inspect=1), by id + content hash */
const inspectCache = new Map<string, unknown>()

/**
 * What a fragment declares about itself — events, captions, its camera, whether
 * it is a window of a continuous film (fragment.inspect, @kadr/runtime) — read
 * in a hidden page that loads the module and never renders it. Cached by the
 * fragment's content hash, so an edit is re-read and nothing else is.
 */
async function inspectFragment(id: string): Promise<unknown> {
  assertId(id)
  await ensureWorkspace()
  if (!existsSync(join(FRAG_DIR(), id, 'index.tsx'))) throw new Error(`no fragment ${id}`)
  const key = `${id}:${fragmentHash(id)}`
  if (inspectCache.has(key)) return inspectCache.get(key)
  const { url } = await ensureServer()
  const win = new BrowserWindow({ show: false, webPreferences: { backgroundThrottling: false } })
  try {
    await win.loadURL(`${url}/?comp=${encodeURIComponent(id)}&inspect=1`)
    const deadline = Date.now() + 30000
    for (;;) {
      const r = await win.webContents.executeJavaScript('window.__kadrInspect ?? null', true).catch(() => null)
      if (r) {
        if (inspectCache.size > 100) inspectCache.clear()
        if ((r as { ok?: boolean }).ok) inspectCache.set(key, r)
        return r
      }
      if (Date.now() > deadline) throw new Error(`inspect ${id}: the page did not answer in 30 s`)
      await new Promise((res) => setTimeout(res, 200))
    }
  } finally {
    if (!win.isDestroyed()) win.destroy()
  }
}

/**
 * Play a fragment frame by frame in a hidden page (player ?collide=1) and
 * report which parts of Kadr's 3D kit intersect, on which frames. Offscreen
 * rendering keeps its frame loop running while nobody looks.
 */
async function collideFragment(id: string, stepSec = 1 / 15): Promise<unknown> {
  assertId(id)
  await ensureWorkspace()
  if (!existsSync(join(FRAG_DIR(), id, 'index.tsx'))) throw new Error(`no fragment ${id}`)
  let frames = 600
  try {
    const meta = JSON.parse(await fs.readFile(join(FRAG_DIR(), id, 'meta.json'), 'utf8'))
    frames = Math.max(1, Math.round(meta.durationInFrames / Math.max(1, Math.round(stepSec * meta.fps))))
  } catch { /* the page knows */ }
  const { url } = await ensureServer()
  const win = new BrowserWindow({
    show: false, width: 960, height: 540, enableLargerThanScreen: true,
    webPreferences: { offscreen: true, backgroundThrottling: false }
  })
  win.webContents.setFrameRate(60)
  try {
    await win.loadURL(`${url}/?comp=${encodeURIComponent(id)}&collide=1&step=${stepSec}`)
    const deadline = Date.now() + 60000 + frames * 1500
    for (;;) {
      const r = await win.webContents.executeJavaScript('window.__kadrCollide ?? null', true).catch(() => null)
      if (r) return r
      if (Date.now() > deadline) throw new Error(`collide ${id}: no answer`)
      await new Promise((res) => setTimeout(res, 300))
    }
  } finally {
    if (!win.isDestroyed()) win.destroy()
  }
}

