export interface FragmentTypeError { file: string; line: number; col: number; code: string; message: string }

/**
 * tsc over ONE fragment with the paths the preview and the render use
 * ('@lib/…' of its project, '@kadr/…'), reporting only errors in the
 * fragment, its project's kadr-lib and Kadr's runtime — not the thousands a
 * whole-workspace check prints for everything else there.
 */
async function typecheckFragment(id: string): Promise<{ ok: boolean; errors: FragmentTypeError[]; more: number }> {
  assertId(id)
  await ensureWorkspace()
  if (!existsSync(join(FRAG_DIR(), id, 'index.tsx'))) throw new Error(`no fragment ${id}`)
  const pd = await projectDirOf(id)
  const key = pd ? projectKey(pd) : null
  const cfgName = `tsconfig.kadr-check-${process.pid}.json`
  const cfg = {
    extends: './tsconfig.json',
    compilerOptions: {
      noEmit: true,
      preserveSymlinks: true,
      baseUrl: '.',
      paths: {
        '@kadr/*': ['src/_kadr/*'],
        ...(key ? { '@lib/*': [`src/_projects/${key}/lib/*`] } : {})
      }
    },
    include: [`src/fragments/${id}/**/*`, 'src/_kadr/assets.d.ts']
  }
  await fs.writeFile(join(WORKSPACE, cfgName), JSON.stringify(cfg, null, 2))
  try {
    const out = await new Promise<string>((resolve) => {
      const child = spawn(join(WORKSPACE, 'node_modules', '.bin', 'tsc'), ['-p', cfgName, '--pretty', 'false'], {
        cwd: WORKSPACE, stdio: ['ignore', 'pipe', 'pipe']
      })
      let text = ''
      child.stdout!.on('data', (c) => { text += c })
      child.stderr!.on('data', (c) => { text += c })
      child.on('error', (e) => resolve(String(e)))
      child.on('close', () => resolve(text))
    })
    const mine = [`src/fragments/${id}/`, 'src/_kadr/', ...(key ? [`src/_projects/${key}/`] : [])]
    const errors: FragmentTypeError[] = []
    for (const line of out.split('\n')) {
      const m = line.match(/^(.+?)\((\d+),(\d+)\): error (TS\d+): (.*)$/)
      if (!m || !mine.some((p) => m[1].startsWith(p))) continue
      errors.push({ file: m[1], line: Number(m[2]), col: Number(m[3]), code: m[4], message: m[5] })
    }
    const LIMIT = 60
    return { ok: errors.length === 0, errors: errors.slice(0, LIMIT), more: Math.max(0, errors.length - LIMIT) }
  } finally {
    await fs.unlink(join(WORKSPACE, cfgName)).catch(() => { /* gone */ })
  }
}

// ------------------------------------------------------------ pixel capture
// When a fragment clip carries GL-only features (masks, 3D, transitions,
// effects), the preview swaps its iframe for true pixels: a hidden offscreen
// window runs the same Player page and streams BGRA frames to the renderer,
// where the fragment becomes a regular compositor layer.

const captures = new Map<string, BrowserWindow>()

async function captureStart(
  getWin: () => BrowserWindow | null,
  id: string,
  url: string,
  w: number,
  h: number,
  fps: number
): Promise<void> {
  if (captures.has(id)) return
  const cw = Math.max(64, Math.round(w))
  const ch = Math.max(36, Math.round(h))
  const win = new BrowserWindow({
    show: false,
    frame: false,
    transparent: true,
    width: cw,
    height: ch,
    // newer Electron clamps even hidden windows to the display they land on —
    // with a portrait-rotated monitor first in the layout, a 1280×720 request
    // came back 1080×720 and captured frames arrived letterboxed + stretched
    enableLargerThanScreen: true,
    // never throttle: a parked hidden window stops repainting on seeks, so
    // paused-editor snapshots captured the PREVIOUS frame (stale-frame bug)
    webPreferences: { offscreen: true, backgroundThrottling: false }
  })
  captures.set(id, win)
  win.setContentSize(cw, ch) // re-assert: creation may still have clamped
  win.webContents.setFrameRate(Math.max(10, Math.min(60, Math.round(fps))))
  // A capture window is invisible, so is whatever goes wrong in it: a WebGL
  // context that could not be created or was lost, a page that crashed. Say
  // so in the editor's session log instead of handing back an empty frame.
  win.webContents.on('console-message', (e: any, ...legacy: any[]) => {
    const level = e?.level ?? legacy[0]
    const msg = String(e?.message ?? legacy[1] ?? '')
    const isError = level === 'error' || level === 3
    if (isError || /webgl|context lost|CONTEXT_LOST/i.test(msg)) {
      getWin()?.webContents.send('fragment:capture-log', { id, level: isError ? 'error' : 'warn', msg: msg.slice(0, 600) })
    }
  })
  win.webContents.on('render-process-gone', (_e, d) => {
    getWin()?.webContents.send('fragment:capture-log', { id, level: 'error', msg: `страница захвата упала: ${d.reason}` })
  })
  win.webContents.on('paint', (_ev, _dirty, image) => {
    const size = image.getSize()
    // BGRA, premultiplied — the compositor shader undoes both
    getWin()?.webContents.send('fragment:frame', {
      id, w: size.width, h: size.height, data: image.getBitmap()
    })
  })
  await win.loadURL(url)
}

/** Snapshots ask for the project's full width; live preview stays ≤1280
    (a full-width BGRA stream is ~500 MB/s over IPC). */
function captureResize(id: string, w: number, h: number) {
  const win = captures.get(id)
  if (!win || win.isDestroyed()) return
  const cw = Math.max(64, Math.round(w))
  const ch = Math.max(36, Math.round(h))
  const [ow, oh] = win.getContentSize()
  if (ow === cw && oh === ch) return
  win.setContentSize(cw, ch)
  win.webContents.invalidate()
}

function captureStop(id: string) {
  const win = captures.get(id)
  captures.delete(id)
  if (win && !win.isDestroyed()) win.destroy()
}

function captureSync(id: string, msg: unknown) {
  const win = captures.get(id)
  if (!win || win.isDestroyed()) return
  win.webContents
    .executeJavaScript(`window.postMessage(${JSON.stringify(msg)}, '*'); 0`, true)
    .catch(() => { /* page mid-load */ })
}

/** The frame the fragment page has really DRAWN (player page v3:
    window.__kadrDrawn) — −1 not ready yet, −2 no window. */
async function captureQuery(id: string): Promise<number> {
  const win = captures.get(id)
  if (!win || win.isDestroyed()) return -2
  try {
    const v = await win.webContents.executeJavaScript('window.__kadrDrawn ?? -1', true)
    return typeof v === 'number' ? v : -1
  } catch {
    return -1
  }
}

export function stopAllCaptures() {
  for (const id of [...captures.keys()]) captureStop(id)
}

// ---------------------------------------------------------------------- IPC

export function registerFragmentIpc(getWin: () => BrowserWindow | null) {
  const send = (id: string, phase: string, progress: number) =>
    getWin()?.webContents.send('fragment:progress', { id, phase, progress })

  ipcMain.handle('fragment:ensure', () =>
    ensureWorkspace((phase, p) => send('workspace', phase, p))
  )
  ipcMain.handle('fragment:server', () => ensureServer())
  ipcMain.handle('fragment:create', (_e, spec: FragmentSpec, projectDir?: string | null) =>
    createFragment(spec, projectDir))
  ipcMain.handle('fragment:delete', (_e, id: string) => deleteFragment(id))
  ipcMain.handle('fragment:relocate', (_e, projectDir: string, ids: string[]) =>
    relocateFragments(projectDir, ids))
  ipcMain.handle('fragment:write-file', (_e, id: string, name: string, content: string) =>
    writeFragmentFile(id, name, content))
  ipcMain.handle('fragment:params-write', (_e, id: string, patch: Record<string, unknown> | null) =>
    writeFragmentParams(id, patch))
  ipcMain.handle('fragment:render', (_e, id: string, opts?: { transparent?: boolean; range?: [number, number] }) => {
    renderCancelled = false
    return renderFragment(id, opts, (p) => send(id, 'render', p))
  })
  ipcMain.handle('fragment:cancel-render', () => cancelFragmentRenders())
  ipcMain.handle('fragment:typecheck', (_e, id: string) => typecheckFragment(id))
  ipcMain.handle('fragment:inspect', (_e, id: string) => inspectFragment(id))
  ipcMain.handle('fragment:collide', (_e, id: string, step?: number) => collideFragment(id, Number(step) || undefined))
  ipcMain.handle('fragment:capture-start', (_e, id: string, url: string, w: number, h: number, fps: number) =>
    captureStart(getWin, id, url, w, h, fps)
  )
  ipcMain.handle('fragment:capture-stop', (_e, id: string) => captureStop(id))
  ipcMain.handle('fragment:capture-resize', (_e, id: string, w: number, h: number) => captureResize(id, w, h))
  ipcMain.handle('fragment:capture-query', (_e, id: string) => captureQuery(id))
  ipcMain.on('fragment:capture-sync', (_e, id: string, msg: unknown) => captureSync(id, msg))
  app.on('before-quit', () => {
    stopServer()
    stopAllCaptures()
  })
}
