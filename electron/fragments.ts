/** A saved project's folder in the workspace (src/_projects/<key>):
    readable, and unique per project path. */
export function projectKey(projectDir: string): string {
  const name = basename(projectDir).normalize('NFKD').replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 24)
  return `${name || 'project'}-${createHash('sha1').update(projectDir).digest('hex').slice(0, 8)}`
}

/** The project a fragment belongs to (its sources live in
    <project>/kadr-fragments/<id>), or null for a workspace-only fragment. */
async function projectDirOf(id: string): Promise<string | null> {
  try {
    const real = await fs.realpath(join(FRAG_DIR(), id))
    return basename(dirname(real)) === 'kadr-fragments' ? dirname(dirname(real)) : null
  } catch {
    return null
  }
}

/**
 * <project>/kadr-lib — the project's shared code, models, fonts and media,
 * imported from any of its fragments as '@lib/…' (no copies per fragment:
 * one project had eight identical copies of its 50 KB film module and of
 * megabytes of model data, kept in step by a shell script). The workspace
 * reaches it through the link src/_projects/<key>/lib, so bare imports inside
 * it (three, react) resolve from the workspace's node_modules like any
 * fragment's. fonts.ts registers kadr-lib/fonts for the preview page.
 */
async function ensureProjectLib(projectDir: string): Promise<string> {
  const lib = join(projectDir, 'kadr-lib')
  await fs.mkdir(lib, { recursive: true })
  const key = projectKey(projectDir)
  const home = join(PROJECTS_DIR(), key)
  await fs.mkdir(home, { recursive: true })
  const link = join(home, 'lib')
  const cur = await fs.readlink(link).catch(() => null)
  if (cur !== lib) {
    await fs.rm(link, { force: true }).catch(() => { /* nothing there */ })
    await fs.symlink(lib, link, linkType)
  }
  await writeManaged(join(home, 'fonts.ts'),
    `// AUTO-GENERATED by Kadr — registers the fonts in kadr-lib/fonts for the preview page.\n` +
    `import 'virtual:kadr-fonts/${key}'\n`)
  return key
}

// npm install and remotion's headless-chrome download may need the user's
// network settings (proxies etc.) — shared with the Claude session config:
// userData/claude-env.json { "env": { "HTTPS_PROXY": "...", ... } }
async function netEnv(): Promise<Record<string, string>> {
  try {
    const p = join(app.getPath('userData'), 'claude-env.json')
    const cfg = JSON.parse(await fs.readFile(p, 'utf8'))
    return cfg?.env ?? {}
  } catch {
    return {}
  }
}

