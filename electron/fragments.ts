async function writeIfMissing(path: string, content: string) {
  try {
    await fs.access(path)
  } catch {
    await fs.writeFile(path, content)
  }
}

/** Kadr-managed file ("do not edit"): follow template changes in place.
    Written to a sidecar and renamed: the dev server must never see a
    truncated file (a plain writeFile is a truncate and then a write — two
    change events, and a request between them compiles the empty one). */
async function writeManaged(path: string, content: string) {
  try {
    if ((await fs.readFile(path, 'utf8')) === content) return
  } catch { /* missing */ }
  const tmp = `${path}.part-${process.pid}`
  await fs.writeFile(tmp, content)
  await fs.rename(tmp, path)
}

/** Rewrite the registry from the folders actually present on disk.
    Project-owned fragments appear here as symlinks — include them too
    (a symlinked Dirent is never isDirectory(); existsSync follows it).
    Two files: index.ts imports everything (remotion's Root), lazy.ts maps
    ids to dynamic imports (the preview's player page — one fragment each).
    Written only when the content changes: every rewrite is a file change the
    dev server reacts to. */
async function regenRegistry() {
  const dirs = (await fs.readdir(FRAG_DIR(), { withFileTypes: true }))
    .filter((d) => d.isDirectory() || d.isSymbolicLink())
    .map((d) => d.name)
    .filter((n) => existsSync(join(FRAG_DIR(), n, 'index.tsx')))
    .sort()
  const head = '// AUTO-GENERATED by Kadr — fragment registry. Do not edit.'
  await writeManaged(join(FRAG_DIR(), 'index.ts'), [
    head,
    ...dirs.map((d, i) => `import { fragment as f${i} } from './${d}'`),
    '',
    'export const fragments = {',
    ...dirs.map((d, i) => `  '${d}': f${i},`),
    '}',
    ''
  ].join('\n'))
  // a project's fonts register BEFORE its fragment module runs
  const loader = async (d: string) => {
    const pd = await projectDirOf(d)
    const key = pd ? projectKey(pd) : null
    return key && existsSync(join(PROJECTS_DIR(), key, 'fonts.ts'))
      ? `  '${d}': () => import('../_projects/${key}/fonts').then(() => import('./${d}')),`
      : `  '${d}': () => import('./${d}'),`
  }
  await writeManaged(join(FRAG_DIR(), 'lazy.ts'), [
    head,
    'export const loaders: Record<string, () => Promise<{ fragment: any }>> = {',
    ...(await Promise.all(dirs.map(loader))),
    '}',
    ''
  ].join('\n'))
}

/** Bring an existing workspace up to WS_DEPS / TSCONFIG in place; true when
    some declared package is not installed yet. Only ADDS: a version the
    user pinned, a dependency of their own, an option they set are kept. */
async function migrateWorkspace(): Promise<boolean> {
  const pkgPath = join(WORKSPACE, 'package.json')
  try {
    const pkg = JSON.parse(await fs.readFile(pkgPath, 'utf8'))
    let changed = false
    const has = (n: string) => !!(pkg.dependencies?.[n] || pkg.devDependencies?.[n])
    for (const [n, v] of Object.entries(WS_DEPS)) if (!has(n)) { (pkg.dependencies ??= {})[n] = v; changed = true }
    for (const [n, v] of Object.entries(WS_DEV_DEPS)) if (!has(n)) { (pkg.devDependencies ??= {})[n] = v; changed = true }
    if (changed) await fs.writeFile(pkgPath, JSON.stringify(pkg, null, 2) + '\n')
  } catch { /* unreadable package.json: npm install will say so */ }
  const tsPath = join(WORKSPACE, 'tsconfig.json')
  try {
    const ts = JSON.parse(await fs.readFile(tsPath, 'utf8'))
    const co = (ts.compilerOptions ??= {})
    let changed = false
    if (!co.baseUrl) { co.baseUrl = '.'; changed = true }
    if (!co.paths?.['@kadr/*']) { co.paths = { ...(co.paths ?? {}), '@kadr/*': ['src/_kadr/*'] }; changed = true }
    if (changed) await fs.writeFile(tsPath, JSON.stringify(ts, null, 2) + '\n')
  } catch { /* hand-edited with comments: leave it alone */ }
  return [...Object.keys(WS_DEPS), ...Object.keys(WS_DEV_DEPS)]
    .some((n) => !existsSync(join(WORKSPACE, 'node_modules', n, 'package.json')))
}

/**
 * src/_projects/<key>/ of projects that are gone (deleted, or a /tmp test
 * project): their lib link dangles. Nothing else refers to them, and opening
 * the project again recreates the folder (ensureProjectLib), so a dangling
 * one is removed — before this they piled up, one per project ever saved.
 * Only folders whose lib is a DANGLING SYMLINK are touched.
 */
let prunedProjects = false
async function pruneProjectLinks(): Promise<void> {
  if (prunedProjects) return
  prunedProjects = true
  let keys: string[] = []
  try { keys = await fs.readdir(PROJECTS_DIR()) } catch { return }
  for (const key of keys) {
    const link = join(PROJECTS_DIR(), key, 'lib')
    const st = await fs.lstat(link).catch(() => null)
    if (!st?.isSymbolicLink()) continue
    if (await fs.stat(link).then(() => true, () => false)) continue // target still there
    await fs.rm(join(PROJECTS_DIR(), key), { recursive: true, force: true }).catch(() => {})
  }
}

async function ensureWorkspace(
  onProgress?: (phase: string, p: number) => void
): Promise<{ dir: string; installed: boolean }> {
  await fs.mkdir(FRAG_DIR(), { recursive: true })
  await pruneProjectLinks()
  await writeIfMissing(join(WORKSPACE, 'package.json'), PKG_JSON)
  await writeManaged(join(WORKSPACE, 'vite.config.ts'), VITE_CONFIG)
  await writeIfMissing(join(WORKSPACE, 'tsconfig.json'), TSCONFIG)
  await writeIfMissing(join(WORKSPACE, 'index.html'), INDEX_HTML)
  // the registry first: the player page imports lazy.ts
  if (!existsSync(join(FRAG_DIR(), 'index.ts')) || !existsSync(join(FRAG_DIR(), 'lazy.ts'))) await regenRegistry()
  await writeManaged(join(WORKSPACE, 'player.tsx'), PLAYER_TSX)
  await writeManaged(join(WORKSPACE, 'src', 'Root.tsx'), ROOT_TSX)
  await fs.mkdir(KADR_DIR(), { recursive: true })
  await writeManaged(join(KADR_DIR(), 'three-preview.tsx'), THREE_PREVIEW_TSX)
  await writeManaged(join(KADR_DIR(), 'runtime.ts'), RUNTIME_TS)
  await writeManaged(join(KADR_DIR(), 'webpack.ts'), WEBPACK_TS)
  await writeManaged(join(KADR_DIR(), 'assets.d.ts'), ASSETS_D_TS)
  await writeManaged(join(KADR_DIR(), 'three.tsx'), KIT_THREE_TSX)
  await writeIfMissing(join(WORKSPACE, 'src', 'index.ts'), INDEX_TS)

  const needInstall = await migrateWorkspace()
  let installed = false
  if (needInstall) {
    onProgress?.('install', 0)
    const extraEnv = await netEnv()
    await new Promise<void>((resolve, reject) => {
      const child = spawn('npm', ['install', '--no-audit', '--no-fund'], {
        cwd: WORKSPACE,
        env: { ...process.env, ...extraEnv },
        stdio: ['ignore', 'pipe', 'pipe']
      })
      let err = ''
      child.stderr.on('data', (c) => { err += c })
      child.on('error', reject)
      child.on('close', (code) => {
        if (code === 0) resolve()
        else reject(new Error(`npm install failed (${code}): ${err.slice(-600)}`))
      })
    })
    installed = true
    onProgress?.('install', 1)
  }
  return { dir: WORKSPACE, installed }
}

// --------------------------------------------------------------- dev server

let server: { child: ChildProcess | null; url: string } | null = null
// overridable so a second, isolated instance (test bench) never shares — and
// never restarts — the working editor's server
const VITE_PORT = Number(process.env.KADR_FRAGMENTS_PORT) || 5621

/** A server (possibly from a previous app run) already serving the page? */
async function probeExisting(): Promise<string | null> {
  try {
    const res = await fetch(`http://127.0.0.1:${VITE_PORT}/`, {
      signal: AbortSignal.timeout(1500)
    })
    const body = await res.text()
    if (res.ok && body.includes('player.tsx')) return `http://127.0.0.1:${VITE_PORT}`
  } catch { /* nothing there */ }
  return null
}

/** something accepts connections on the port (a server, maybe not answering yet) */
const portTaken = () => new Promise<boolean>((resolve) => {
  const sock = connect({ host: '127.0.0.1', port: VITE_PORT })
  const done = (v: boolean) => { sock.destroy(); resolve(v) }
  sock.once('connect', () => done(true))
  sock.once('error', () => done(false))
  sock.setTimeout(1000, () => done(false))
})

/**
 * The server of an earlier run, waited for while it RESTARTS. ensureWorkspace
 * rewrites vite.config.ts when Kadr's template changed, and a running vite
 * restarts itself on that — for a few seconds its port is taken but nothing
 * answers. Probing once then started a second vite, which died on «Port 5621
 * is already in use», and the preview showed that error instead of the
 * fragments (met right after an update of the template).
 */
async function awaitExisting(ms: number): Promise<string | null> {
  const until = Date.now() + ms
  for (;;) {
    const url = await probeExisting()
    if (url) return url
    if (Date.now() > until || !(await portTaken())) return null
    await new Promise((r) => setTimeout(r, 400))
  }
}

let starting: Promise<{ url: string }> | null = null

async function ensureServer(): Promise<{ url: string }> {
  if (server && (!server.child || server.child.exitCode === null)) return { url: server.url }
  // one start at a time: two callers at once used to spawn two servers
  starting ??= startServer().finally(() => { starting = null })
  return starting
}

async function startServer(): Promise<{ url: string }> {
  server = null
  await ensureWorkspace()
  const existing = await awaitExisting(20000)
  if (existing) {
    server = { child: null, url: existing }
    return { url: existing }
  }
  // a watchdog shell kills vite when this process dies — orphaned children
  // inherit Electron's listening sockets and would block the next launch.
  // The bin runs directly (NOT via npx — npx makes vite a grandchild the
  // watchdog's kill couldn't reach).
  const child = spawn('sh', ['-c',
    `"./node_modules/.bin/vite" --port ${VITE_PORT} --strictPort & V=$!; ` +
    `(while kill -0 ${process.pid} 2>/dev/null; do sleep 3; done; kill $V 2>/dev/null) & ` +
    'wait $V'
  ], {
    cwd: WORKSPACE,
    env: { ...process.env },
    stdio: ['ignore', 'pipe', 'pipe']
  })
  let adopted = false
  const url = await new Promise<string>((resolve, reject) => {
    let out = ''
    const timer = setTimeout(() => reject(new Error('vite start timeout: ' + out.slice(-400))), 30000)
    const onData = (c: Buffer) => {
      out += c
      // vite's banner carries ANSI colors that split the port digits
      // ("http://127.0.0.1:\x1b[1m5621") — strip them before matching, or a
      // cold start never resolves and every first fragment use flakes
      const clean = out.replace(/\x1b\[[0-9;]*m/g, '')
      const m = clean.match(/(http:\/\/127\.0\.0\.1:\d+)/)
      if (m) {
        clearTimeout(timer)
        resolve(m[1])
      }
    }
    child.stdout!.on('data', onData)
    child.stderr!.on('data', onData)
    child.on('error', (e) => { clearTimeout(timer); reject(e) })
    child.on('close', (code) => { clearTimeout(timer); reject(new Error(`vite exited ${code}: ${out.slice(-400)}`)) })
  }).catch(async (e) => {
    // lost a race for the port to a server that came up meanwhile: use that one
    const other = /already in use/i.test(String(e?.message)) ? await awaitExisting(15000) : null
    if (!other) throw e
    adopted = true
    return other
  })
  server = { child: adopted ? null : child, url }
  return { url }
}

function stopServer() {
  server?.child?.kill()
  server = null
}

