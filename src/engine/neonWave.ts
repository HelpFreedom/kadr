// Neon wave: an audio-reactive Remotion fragment that reproduces the user's
// Blender preset (a glowing sine line whose wiggle frequency and height follow
// loudness) without Blender. The loudness envelope is computed in main
// (audio:envelope — Blender's "Bake Sound" follower, verified exact) and baked
// into the generated TSX together with the style, like auto-captions. Geometry
// is the preset's node graph in closed form (verified against Blender's
// evaluated mesh to 0.03 px); colour/glow/streaks are a canvas imitation of
// EEVEE + Filmic + Glare, calibrated against the preset's rendered frames.
import { useEditor } from '@/state/store'
import type { FragmentSpec } from '@shared/types'
import { collectRangeAudio } from './subtitles'
import { createFragment } from './fragments'

export interface NeonWaveStyle {
  // ---- geometry (Blender units; the preset's camera gives 128.6 px/unit at 1920 wide)
  /** points along the line */
  samples: number
  /** px per unit at a 1920-wide frame (scales with width) */
  pxPerUnit: number
  /** tube radius, units */
  tubeRadius: number
  /** height factor: z = amp · e · (wave − 0.5) · window */
  amp: number
  /** wave frequency factor: sin(wiggle · x · e + phase · t − π/2) */
  wiggle: number
  /** wave phase speed, rad/s (frame/2 at the preset's 24 fps) */
  phase: number
  /** static window frequency: sin(window · x − π/2) */
  window: number
  /** window ColorRamp: [position, value] — piecewise linear */
  ramp: [number, number][]
  /** Blender compositor Lens Distortion «Distort» (−0.3). Applied exactly like Blender's
      ScreenLensDistortion: per-axis normalised uv·sc with sc = 1/(1+max k) (the whole picture
      shrinks towards the centre for negative k), source = uv·d, d = 1/(1+√(1−4k·r²)). */
  distortion: number
  // ---- colour
  /** emission ColorRamp stops [position, [r,g,b] linear 0..1] */
  colorStops: [number, [number, number, number]][]
  /** colour wave over normalised height: sin(colorWave · zn + colorPhase · t − π/2) */
  colorWave: number
  /** rad/s (frame/20 at 24 fps) */
  colorPhase: number
  /** core tone-mapping: sRGB(1 − exp(−coreExposure · c)) — emission 10× through Filmic (4.9 matches the preset's render) */
  coreExposure: number
  // ---- glow
  /** core stroke width multiplier over the tube diameter */
  coreWidthMul: number
  /** soft passes of the saturated colour: [blur px, alpha, stroke width px] at 1920 wide, SOURCE space (the glow itself comes from the streaks) */
  halo: [number, number, number][]
  /** Glare Streaks — the preset's only glow: the saturated line copied along `angles` (degrees) every `step` source px, alpha fade^j; calibrated to 0.3·exp(−d/28 px) in the output */
  streak: { strength: number; fade: number; copies: number; step: number; angles: number[] }
  /** Lens Distortion «Dispersion» (0.2): each channel gets its own k — R = distort + 0.25·d,
      B = distort − 0.25·d — so blue reaches furthest out (the blue tails at the line ends) */
  dispersion: number
  /** canvas resolution factor used only in the live preview (the render is 1) */
  previewScale: number
  background: string
}

