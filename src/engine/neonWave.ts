/** Generate the fragment source for an envelope (one value per frame) and a style. */
export function neonWaveTsx(env: number[], meta: FragmentSpec, style: NeonWaveStyle = NEON_WAVE_DEFAULTS): string {
  const frames = Math.max(1, meta.durationInFrames)
  const fixed = env.slice(0, frames).map((v) => +(+v || 0).toFixed(4))
  while (fixed.length < frames) fixed.push(fixed.length ? fixed[fixed.length - 1] : 0)
  return TSX.replace('__ENV__', JSON.stringify(fixed)).replace('__STYLE__', JSON.stringify(style, null, 2))
}

export interface NeonWaveOpts {
  range: { start: number; end: number }
  /** 'mix' = every audible track in the range; {trackId} = only that track's mix */
  source?: 'mix' | { trackId: string }
  style?: Partial<NeonWaveStyle>
  /** fragment name (composition id derives from it) */
  name?: string
}

/**
 * Compute the loudness envelope of the range (WYSIWYG mix through the export
 * segment graph), scaffold an opaque fragment over the range and bake the
 * envelope + style into its TSX. Returns the clip (selected, live preview in
 * the iframe overlay) and the entry file for further hand/Claude tuning.
 */
export async function neonWave(opts: NeonWaveOpts) {
  const st = () => useEditor.getState()
  const project = st().project
  const { start, end } = opts.range
  if (!(end > start)) throw new Error('empty range')
  const source = opts.source ?? 'mix'
  const filter = source === 'mix' ? undefined : { trackIds: [source.trackId] }
  const segments = collectRangeAudio(project, start, end, filter)
  // the same clamp createFragment applies — the envelope must be one value per composition frame
  const fps = Math.max(60, project.fps)
  const duration = end - start
  const env = await window.kadr.audioEnvelope({ audioSegments: segments, duration, fps })
  // only now scaffold: a failed mix leaves no orphan fragment/clip behind
  const frag = await createFragment({ name: opts.name || 'wave', start, end, transparent: false })
  const style = { ...NEON_WAVE_DEFAULTS, ...(opts.style || {}) }
  await window.kadr.writeTextFile(frag.entry, neonWaveTsx(env, frag.meta, style))
  st().select([frag.clipId])
  let peak = 0
  for (const v of env) if (v > peak) peak = v
  return { clipId: frag.clipId, fragmentId: frag.id, entry: frag.entry, frames: frag.meta.durationInFrames, peak }
}
